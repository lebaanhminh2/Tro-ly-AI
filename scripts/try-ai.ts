import { GeminiTrial } from '../src/ai/gemini.ts';
import { mkdirSync, readFileSync, renameSync, writeFileSync, openSync, closeSync, unlinkSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
import { decide } from '../src/ai/policy.ts';
import { TrialFlow } from '../src/ai/trial-flow.ts';
import { syntheticInput as cleanInput, cases } from '../tests/ai-cases.ts';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
const live = args.includes('--live');
const batch = args.includes('--batch');
const id = args.find(a => /^T\d\d$/.test(a)) ?? 'T07';
const selected = cases.find(c => c[0] === id);
const BATCH_IDS = ['T01', 'T03', 'T06', 'T08', 'T10', 'T12'] as const;
const CAMPAIGN_LIMIT = 7; // One earlier T07 + six requests approved on 2026-09-11.
const CAMPAIGN_BASELINE = 1;
const WAIT_MS = 16_000;

type BudgetState = { campaign: string; used: number; limit: number; updatedAt: string };
export class PersistentBudget {
  private path: string;
  private limit: number;
  private baseline: number;
  constructor(path: string, limit = CAMPAIGN_LIMIT, baseline = CAMPAIGN_BASELINE) {
    this.path = path;
    this.limit = limit;
    this.baseline = baseline;
  }
  read(): BudgetState {
    try {
      const value = JSON.parse(readFileSync(this.path, 'utf8')) as Partial<BudgetState>;
      if (value.campaign !== 'persona-trial-2026-09-11' || !Number.isInteger(value.used) ||
          value.limit !== this.limit || (value.used as number) < this.baseline || (value.used as number) > this.limit)
        throw new Error('INVALID_PERSISTENT_BUDGET');
      return value as BudgetState;
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
      return { campaign: 'persona-trial-2026-09-11', used: this.baseline, limit: this.limit, updatedAt: new Date().toISOString() };
    }
  }
  reserve(): BudgetState {
    mkdirSync(dirname(this.path), { recursive: true });
    const lock = `${this.path}.lock`;
    const descriptor = openSync(lock, 'wx');
    try {
    const state = this.read();
    if (state.used >= state.limit) throw new Error('PERSISTENT_TRIAL_BUDGET_EXHAUSTED');
    const next = { ...state, used: state.used + 1, updatedAt: new Date().toISOString() };
    mkdirSync(dirname(this.path), { recursive: true });
    const temporary = `${this.path}.tmp`;
    writeFileSync(temporary, `${JSON.stringify(next, null, 2)}\n`, { encoding: 'utf8', flag: 'wx' });
    renameSync(temporary, this.path);
    return next;
    } finally { closeSync(descriptor); unlinkSync(lock); }
  }
}


async function run() {
  if (args.length === 1 && args[0] === '--flow') {
    const flow = new TrialFlow(() => Date.parse('2026-09-11T10:00:00+07:00'));
    const text = 'còn bài thực hành vẽ';
    const raw = { kind: 'proposal' as const, reply: 'bao giờ nộp?', draft: {
      operation: 'capture_task' as const, entityId: null, field: 'title' as const, value: 'bài thực hành vẽ',
      certainty: 'confirmed' as const, evidence: text } };
    const capture = flow.receive('user-test', text, raw);
    console.log(JSON.stringify({ mode: 'OFFLINE FLOW — synthetic model response', raw, decision: capture, beforeConfirmation: flow.snapshot('user-test') }));
    console.log(flow.confirm('user-test', capture.proposalId!));
    flow.selectDeadline('user-test', flow.snapshot('user-test')[0]!.id);
    const chat = { kind: 'chat' as const, reply: 'offline', draft: null };
    console.log(flow.receive('user-test', 'ngày mai', chat));
    const change = flow.receive('user-test', '12/09/2026 20:00', chat);
    console.log(change, flow.snapshot('user-test'));
    console.log(flow.confirm('user-test', change.proposalId!), flow.snapshot('user-test'));
    return;
  }
  if (!selected || args.some(a => !['--live', '--batch', '--confirm-synthetic-data', ...cases.map(c => c[0])].includes(a)) || (batch && !live))
    throw new Error('Use: npm run try:ai -- [T01..T12] [--live --confirm-synthetic-data] OR --batch --live --confirm-synthetic-data');
  const inputs = cleanInput(id);
  try {
    if (!live) {
      const mock = { kind: 'chat', reply: 'ừ, tớ không giục thêm. muốn kể không?', draft: null };
      const client = new GeminiTrial({ apiKey: 'offline-placeholder', model: 'offline-mock', transport: async () =>
        new Response(JSON.stringify({ candidates: [{ finishReason: 'STOP', content: { parts: [{ text: JSON.stringify(mock) }] } }] })) });
      const result = await client.generate(inputs.turns, inputs.context, inputs.entities.map(e => e.id));
      console.log(JSON.stringify({ mode: 'OFFLINE MOCK — not generated by Gemini; no persona quality verdict', caseId: id,
        ...result, decision: decide(result.output, inputs.turns, { userId: 'user-test', entities: inputs.entities }) }, null, 2));
    } else {
      if (!args.includes('--confirm-synthetic-data') || process.env.GEMINI_FREE_TIER_VERIFIED !== 'true')
        throw new Error('Live trial requires explicit synthetic-data consent and verified free tier.');
      // Anchor to repository, never cwd or user-supplied env paths.
      const resultsDir = fileURLToPath(new URL('../trial-results/', import.meta.url));
      const budgetPath = resolve(resultsDir, 'persona-budget.json');
      const reportPath = resolve(resultsDir, `persona-${Date.now()}-${randomUUID()}.json`);
      // No live calls authorized for this revision; prior campaign remains untouched.
      const campaignApproved = false;
      if (!campaignApproved) throw new Error('LIVE_CAMPAIGN_REQUIRES_NEW_APPROVAL');
      const budget = new PersistentBudget(budgetPath);
      const ids: readonly string[] = batch ? BATCH_IDS : [id];
      const results: unknown[] = [];
      for (let index = 0; index < ids.length; index++) {
        const caseId = ids[index]!;
        budget.reserve(); // Reserve before network: ambiguous failures still consume campaign budget.
        const input = cleanInput(caseId);
        const client = new GeminiTrial({ apiKey: process.env.GEMINI_API_KEY ?? '', model: process.env.GEMINI_MODEL ?? '', maxRequests: 1 });
        try {
          const result = await client.generate(input.turns, input.context, input.entities.map(e => e.id));
          const decision = decide(result.output, input.turns, { userId: 'user-test', entities: input.entities });
          results.push({ caseId, status: 'ok', input, decision, ...result });
        } catch (error) {
          results.push({ caseId, status: 'error', error: error instanceof Error ? error.message : 'TRIAL_FAILED' });
        }
        mkdirSync(dirname(reportPath), { recursive: true });
        writeFileSync(reportPath, `${JSON.stringify({ mode: 'LIVE — human review required', results }, null, 2)}\n`, 'utf8');
        console.log(JSON.stringify(results.at(-1), null, 2));
        if ((results.at(-1) as { status: string }).status === 'error') throw new Error('BATCH_STOPPED_ON_ERROR');
        if (index < ids.length - 1) await new Promise(resolveWait => setTimeout(resolveWait, WAIT_MS));
      }
    }
  } catch (error) {
    console.error(error instanceof Error ? error.message : 'TRIAL_FAILED');
    process.exitCode = 1;
  }
}

const isMain = process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) run().catch(error => { console.error(error instanceof Error ? error.message : 'TRIAL_FAILED'); process.exitCode = 1; });
